const fs=require('fs'), path=require('path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const checks=[]; const check=(n,o)=>{checks.push([n,!!o]); if(!o) console.error('FAIL:',n)};
const html=read('frontend/admin-applications/index.html');
const js=read('frontend/admin-applications/admin.js');
const css=read('frontend/admin-applications/admin.css');
check('Registered users section exists', html.includes('id="registeredUsersList"') && html.includes('Registered users'));
check('Registered users count exists', html.includes('id="registeredUsersCount"'));
check('User search exists', html.includes('id="registeredUsersSearch"'));
check('Edit user dialog exists', html.includes('id="editRegisteredUserDialog"'));
check('Edit confirmation available', html.includes('/edit-confirm.js?v=217-user-list') || html.includes('id="registeredUserActionDialog"'));
check('Delete confirmation available', html.includes('/delete-confirm.js?v=217-user-list') || html.includes('id="registeredUserActionDialog"'));
check('Loads users API', js.includes('api("/api/users")'));
check('Loads roles for edit', js.includes('api("/api/users/roles")'));
check('Loads customers for technician assignment', js.includes('api("/api/customers")'));
check('Renders Edit action', js.includes('data-edit-registered-user'));
check('Renders Delete action', js.includes('data-delete-registered-user'));
check('Edit uses protected confirmation', js.includes('window.belmConfirmEdit') || js.includes('confirmRegisteredUserAction'));
check('Delete uses protected confirmation', js.includes('window.belmConfirmDelete') || js.includes('confirmRegisteredUserAction'));
check('Delete uses Recycle Bin backend route', js.includes('method: "DELETE"'));
check('Prevents self-delete button', js.includes("isSelf ? '<span class=\"you-badge\">You</span>'"));
check('Refresh reloads user list', js.includes('loadRegisteredUsers()'));
check('User table styling exists', css.includes('.registered-users-table'));
const failed=checks.filter(x=>!x[1]); console.log(`V217 targeted checks: ${checks.length-failed.length}/${checks.length} PASS`); if(failed.length) process.exit(1);
