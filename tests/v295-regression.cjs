check('approval deducts store', api.includes("UPDATE customer_store_items SET qty_on_hand = ?, updated_at = NOW()"));
check('approval creates expense', api.includes("SET status='APPROVED'") && api.includes("'CUSTOMER_STORE', $balanceAfter"));
