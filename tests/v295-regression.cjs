check('saved list table schema', schema.includes('CREATE TABLE IF NOT EXISTS customer_machine_spare_list_items'));
check('store approval table schema', schema.includes('CREATE TABLE IF NOT EXISTS customer_store_issue_requests'));
check('store check backend', api.includes("if ($sub === 'spare-store-check'"));
check('spare workspace backend', api.includes("if ($sub === 'spare-workspace'"));
