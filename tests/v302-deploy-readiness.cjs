const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
let pass = 0;
function check(name, fn) { try { fn(); console.log('PASS', name); pass++; } catch (e) { console.error('FAIL', name); throw e; } }
const apache = read('docker/belm-apache.conf');
const schema = read('backend/schema.sql');
const migrate = read('backend/scripts/migrate.php');
const reset = read('backend/scripts/reset.php');
const health = read('backend/index.php');
const render = read('render.yaml');
const readme = read('README_RENDER.txt');
const repair = read('backend/repair_admin.sql');
const v301 = read('tests/v301-regression.cjs');
const theme = read('frontend/theme-manager.js');
const belmTheme = read('frontend/belm-theme.css');
const servicePage = read('frontend/customer-service-request/index.html');
const procurementJs = read('frontend/customer-machine-expenses/expenses.js');
const procurementHtml = read('frontend/customer-procurement/index.html');
check('Docker friendly route accepts @BELM', () => assert.match(apache, /a-zA-Z0-9@-/));
check('schema no known default admin hash', () => assert.doesNotMatch(schema, /uXo8bDdT3YV7BlM7V4oOR/));
check('schema no plaintext default password', () => assert.doesNotMatch(schema, /ChangeMe123!/));
check('migration requires secure bootstrap secret', () => { assert.match(migrate, /INITIAL_ADMIN_PASSWORD/); assert.match(migrate, /strlen\(\$initialPassword\) < 12/); });
check('migration detects legacy known hash', () => assert.match(migrate, /legacyKnownHash/));
check('Render prompts for initial admin secret', () => assert.match(render, /key: INITIAL_ADMIN_PASSWORD\s+sync: false/s));
check('health schema version current', () => {
  const m = /'schemaVersion' => '(\d+)-/.exec(health);
  assert.ok(m && Number(m[1]) >= 301, 'schemaVersion should be >= 301');
});
check('health checks V301 billing tables', () => { for (const x of ["'invoices'", "'payments'", "'proforma_invoices'"]) assert.match(health, new RegExp(x)); });
check('health checks V301 columns', () => { for (const x of ['signed_copy_data','billing_status','source_job_card_id']) assert.match(health, new RegExp(x)); });
check('incomplete schema returns 503', () => assert.match(health, /\$healthReady \? 200 : 503/));
check('health seeded admin lookup uses stable id', () => assert.match(health, /00000000-0000-4000-8000-000000000003/));
check('full reset preserves admin password', () => assert.match(reset, /preservedAdminPasswordHash/));
check('full reset preserves edit and delete PINs', () => { assert.match(reset, /preservedDeletePin/); assert.match(reset, /preservedEditPin/); });
check('full reset no public default credential message', () => assert.doesNotMatch(reset, /ChangeMe123!/));
check('README no public default password', () => assert.doesNotMatch(readme, /ChangeMe123!/));
check('repair script no known default password or PIN', () => { assert.doesNotMatch(repair, /ChangeMe123!|uXo8bDdT3YV7BlM7V4oOR|"1234"/); });
check('repair script handles stable admin id conflict', () => assert.match(repair, /ON CONFLICT \(id\) DO UPDATE/));
check('V299 rolling-session recovery preserved', () => { assert.match(theme, /fetchWithStableSession/); assert.match(theme, /auth\/refresh/); });
check('V300 night-friendly report theme preserved', () => { assert.match(belmTheme, /data-checkup-tab=\"jobcards\"/); assert.match(belmTheme, /html\[data-theme=\"dark\"\] \.belm-checked-report-modal/); });
check('V298 Spare & Service Request wording preserved', () => assert.match(servicePage, /Spare &amp; Service Request|Spare & Service Request/));
check('V298 shortage selection and BELM handoff preserved', () => { assert.match(procurementHtml, /Select Shortage/); assert.match(procurementHtml, /Send Selected to BELM/); assert.match(procurementJs, /procurement-belm-supply/); });
check('V301 regression remains packaged', () => assert.match(v301, /job card stores issuer/));
console.log(`${pass}/22 V302 deploy-readiness checks passed`);
