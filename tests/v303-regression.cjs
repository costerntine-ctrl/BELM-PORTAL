const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
let pass=0,fail=0;
function check(name,ok){if(ok){console.log('PASS',name);pass++;}else{console.error('FAIL',name);fail++;}}
const helpers=read('backend/config/helpers.php');
const auth=read('backend/api/auth.php');
const app=read('frontend/customer-app.js');
const html=read('frontend/customer-app.html');
const apache=read('docker/belm-apache.conf');
const ht=read('frontend/.htaccess');
const home=read('frontend/portal-home.html');
const manifest=read('frontend/belm-app.webmanifest');
const sw=read('frontend/belm-sw.js');
const portal=read('frontend/portal-tools.js');
const publicRules=read('public_website_patch/HTACCESS_APP_RULES.txt');
const publicWrapper=read('public_website_patch/belm_app.php');
const publicRegister=read('public_website_patch/client_register.php');
check('canonical public_login_url exists', helpers.includes("return public_app_base_url() . '/login';"));
check('customer generated login uses canonical URL', /function customer_portal_url[\s\S]*?return public_login_url\(\);/.test(helpers));
check('staff generated login uses canonical URL', /function belm_staff_login_url[\s\S]*?return public_login_url\(\);/.test(helpers));
check('unified backend login remains enabled', auth.includes("$action === 'unified-login'"));
check('canonical /login served by Apache', apache.includes('RewriteRule ^login/?$ /customer-app.html [END]'));
check('legacy /app aliases redirect to /login', apache.includes('RewriteRule ^app(?:/[a-zA-Z0-9@-]+)?/?$ /login [R=302,L]'));
check('role-specific legacy logins redirect', apache.includes('RewriteRule ^(?:admin/login|portal/login)/?$ /login [R=302,L]'));
check('static htaccess supports canonical login', ht.includes('RewriteRule ^login/?$ /customer-app.html [END]'));
check('home page uses one login link', home.includes('href="/login"') && home.includes('Portal Login'));
check('PWA opens canonical login', manifest.includes('"start_url": "/login"'));
check('login accepts email or Customer Portal ID', html.includes('Email / Customer Portal ID') && html.includes('type="text"'));
check('canonical login does not quick-resume saved portal sessions', !app.includes('quickResume('));
check('canonical login waits for explicit login button click', html.includes('id="loginButton" class="primary" type="button"') && app.includes("button.addEventListener('click',login)"));
check('canonical login blocks form autosubmit from autofill', app.includes("form.addEventListener('submit',event=>event.preventDefault())"));
check('login posts to unified endpoint', app.includes("fetch('/api/auth/unified-login'"));
check('unauthenticated technician workspace returns to one login', portal.includes("window.location.replace('/login')"));
check('service worker cache bumped', sw.includes('belm-app-v303-unified-login'));
check('public website exposes one /login wrapper', publicRules.includes('RewriteRule ^login/?$ /belm_app.php') && publicWrapper.includes("$portalPath = '/login';"));
check('public legacy app links converge to login', publicRules.includes('RewriteRule ^app/([A-Za-z0-9@-]+)/?$ /login [R=302,L]'));
check('public registration stays separate from login', publicRegister.includes('/apply/'));
console.log(`${pass}/${pass+fail} V303 checks passed`);if(fail)process.exit(1);
