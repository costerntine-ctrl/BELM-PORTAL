const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const render=read('render.yaml');
const start=read('docker/start-render.sh');
const db=read('backend/config/database.php');
const login=read('frontend/customer-app.js');
const loginHtml=read('frontend/customer-app.html');
const sw=read('frontend/belm-sw.js');
const health=read('backend/index.php');
const migrate=read('backend/scripts/migrate.php');
const schema=read('backend/schema.sql');
let pass=0,fail=0;
function t(name,cond){try{const ok=typeof cond==='function'?cond():cond;if(!ok)throw new Error('failed');console.log('PASS',name);pass++;}catch(e){console.error('FAIL',name,e.message);fail++;}}
t('static Render health check',render.includes('healthCheckPath: /live.txt'));
t('static liveness file exists',fs.existsSync(path.join(root,'frontend/live.txt')));
t('Apache remains foreground immediately',start.includes('exec apache2-foreground'));
t('migration is delayed after web bind',start.includes('BELM_MIGRATION_START_DELAY:-6'));
t('migration remains background',/\) &\s*exec apache2-foreground/.test(start));
t('DB connect timeout is bounded',db.includes('DB_CONNECT_TIMEOUT')&&db.includes('connect_timeout=%d'));
t('DB statement timeout is bounded',db.includes('DB_STATEMENT_TIMEOUT_MS')&&db.includes('SET statement_timeout'));
t('DB lock timeout is bounded',db.includes('DB_LOCK_TIMEOUT_MS')&&db.includes('SET lock_timeout'));
t('login has bounded fetch helper',login.includes('fetchWithTimeout')&&login.includes('70000'));
t('login gives wake feedback',login.includes('Server waking up…'));
t('login has timeout retry message',login.includes('Server did not respond in time'));
t('login HTML uses V354-or-later JS',loginHtml.includes('/customer-app.js?v=354-fast-wake')||loginHtml.includes('/customer-app.js?v=355-json-api'));
t('service worker uses V354-or-later cache',sw.includes("const CACHE='belm-app-v354-fast-wake-loading-guard';")||sw.includes("const CACHE='belm-app-v355-json-api-clean-response';"));
t('login shell is cache-first',sw.includes("caches.match('/customer-app.html')")&&sw.includes('isLoginShell'));
t('API requests bypass SW cache',sw.includes("url.pathname.startsWith('/api/')"));
t('V354-or-later health marker active',health.includes("'schemaVersion' => '354-fast-wake-loading-guard'")||health.includes("'schemaVersion' => '355-json-api-clean-response'"));
t('V354-or-later migration release active',migrate.includes("const BELM_RELEASE = '354-fast-wake-loading-guard';")||migrate.includes("const BELM_RELEASE = '355-json-api-clean-response';"));
t('V350 data safety remains active',migrate.includes('DATA_SAFETY_BLOCK')&&migrate.includes('belm_predeploy_ids'));
t('schema unchanged by V354',!schema.includes('V354'));
console.log(`RESULT ${pass} passed, ${fail} failed`);process.exit(fail?1:0);
